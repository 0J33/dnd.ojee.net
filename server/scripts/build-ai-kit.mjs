// Regenerate server/ai/kit.cjs from the client's data modules:
//   node scripts/build-ai-kit.mjs      (needs client/node_modules for esbuild)
// Run it after changing client/src/data/{encounters,presets,scenes,mapKit,tiles}.js
// or client/src/ai/profanity.js. The output is committed: production installs
// only the server.
import { createRequire } from 'module';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(path.join(here, '..', '..', 'client', 'package.json'));
const esbuild = require('esbuild');

await esbuild.build({
  entryPoints: [path.join(here, 'ai-kit-entry.mjs')],
  outfile: path.join(here, '..', 'ai', 'kit.cjs'),
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node20',
  legalComments: 'none',
  banner: { js: '// GENERATED by server/scripts/build-ai-kit.mjs from client/src - do not edit by hand.' },
});
console.log('wrote server/ai/kit.cjs');
